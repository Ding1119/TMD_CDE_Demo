"""Curated seed knowledge for TMD CDE development.

What is in here
---------------
* NIH HEAL Initiative CDE Program: core adult pain CDEs (HEAL-required for HEAL-funded
  pain studies) and the HEAL "Facial Pain" supplemental CRFs (DC/TMD Symptom
  Questionnaire, DC/TMD Examination Form, Jaw Functional Limitation Scale).
* DC/TMD Axis I / Axis II protocol elements (INfORM / IADR).
* BDSC-curated, EHR-oriented elements (diagnosis codes, comorbid overlapping pain
  conditions, treatments, imaging) whose value sets are needed for the future EHR layer.

Design notes
------------
* Elements are recorded at the score / measure level, with definitions written in our
  own words. Item wording of licensed instruments (BPI, PROMIS, PCS, PHQ/GAD, JFLS, OBC,
  GCPS) is intentionally NOT reproduced: import the official HEAL CDE .xlsx / REDCap
  dictionaries from the HEAL CDE Repository (Sources page -> Upload) to add item-level CDEs.
* Scoring ranges follow the DC/TMD Self-report Instrument Scoring Manual and the HEAL CRFs;
  every element is a DRAFT for expert review (Delphi), not a released standard.
* Codes were checked against CMS/NCHS ICD-10-CM, LOINC, CDT and WHO ATC listings at the
  time of writing; the Terminology Mapping Agent and reviewers must still confirm them.
* CPT (AMA) and CDT (ADA) are licensed code sets: only code numbers are referenced here, with neutral
  labels instead of the official descriptors. Obtain descriptors from the code owners.
"""
