def m(system: str, code: str, display: str, relation: str = "exact", confidence: float = 0.9, note: Optional[str] = None):
    return {"system": system, "code": code, "display": display, "relation": relation, "confidence": confidence, "note": note}


def pv(code, label, system=None, concept=None):
    d = {"code": str(code), "label": label}
    if system:
        d.update({"concept_system": system, "concept_code": concept})
    return d


